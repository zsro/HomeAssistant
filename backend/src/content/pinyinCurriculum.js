function buildLesson(spec) {
  const teachingFlow = spec.teachingFlow || createGenericFlow(spec);

  return lesson(spec.id, spec.title, {
    tagline: spec.tagline,
    focus: spec.focus,
    goals: spec.goals,
    practiceWords: spec.practiceWords,
    practiceSentence: spec.practiceSentence,
    miniTask: spec.miniTask,
    checkpoints: spec.checkpoints,
    lessonType: spec.lessonType,
    lessonBadge: spec.lessonBadge,
    previewLesson: spec.previewLesson,
    assetNotes: spec.assetNotes || [],
    teachingFlow,
  });
}

