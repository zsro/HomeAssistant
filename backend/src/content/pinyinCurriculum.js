function lesson(id, title, options) {
  return {
    id,
    title,
    durationMinutes: 12,
    ...options,
  };
}

function createAsset(label, solution) {
  return {
    label,
    status: 'pending',
    solution,
  };
}

function createStep(id, title, options) {
  return {
    id,
    title,
    teacherPrompt: '',
    tvScene: '',
    controllerScene: '',
    interaction: '',
    feedback: '',
    controllerMode: 'tap',
    highlights: [],
    resources: [],
    ...options,
  };
}

function createStage(id, title, summary, steps) {
  return {
    id,
    title,
    summary,
    steps,
  };
}

