function buildCurriculum() {
  let order = 1;

  return curriculumStages.map((stage, stageIndex) => {
    const lessons = stage.lessons.map((item, lessonIndex) => {
      let stepCursor = 1;
      const teachingFlow = item.teachingFlow.map((flowStage, flowStageIndex) => {
        const steps = flowStage.steps.map((step, stepIndex) => ({
          ...step,
          stageId: flowStage.id,
          stageTitle: flowStage.title,
          stageOrder: flowStageIndex + 1,
          stageStepIndex: stepIndex + 1,
          stepIndex: stepCursor++,
        }));

        return {
          ...flowStage,
          order: flowStageIndex + 1,
          stepCount: steps.length,
          steps,
        };
      });

      const steps = teachingFlow.flatMap((flowStage) => flowStage.steps);

      return {
        ...item,
        order: order++,
        stageId: stage.id,
        stageTitle: stage.title,
        stageIndex: stageIndex + 1,
        stageLessonIndex: lessonIndex + 1,
        teachingFlow,
        steps,
        totalStepCount: steps.length,
      };
    });

    return {
      ...stage,
      lessonCount: lessons.length,
      estimatedMinutes: lessons.reduce((total, item) => total + item.durationMinutes, 0),
      lessons,
    };
  });
}

const stages = buildCurriculum();
const lessons = stages.flatMap((stage) => stage.lessons);
const lessonMap = new Map(lessons.map((item) => [item.id, item]));

function getCurriculumStages() {
  return stages;
}

function getCurriculumLessons() {
  return lessons;
}

function getLessonById(lessonId) {
  return lessonMap.get(lessonId) || null;
}

